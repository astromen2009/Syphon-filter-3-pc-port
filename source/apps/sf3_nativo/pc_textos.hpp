inline std::string translateWith(const std::string& s, const std::vector<std::pair<std::string, std::string>>& tab);

inline std::string translateLang(const std::string& s, int lang);
inline std::string translateWith(const std::string& s, const std::vector<std::pair<std::string, std::string>>& tab) {
  if (s.empty()) return s;
  std::string out;
  std::size_t i = 0;
  while (i < s.size()) {
    bool done = false;
    for (const auto& [es, en] : tab) {
      if (s.compare(i, es.size(), es) != 0) continue;
      const bool leftOk = i == 0 || !isLetter(static_cast<unsigned char>(s[i - 1])) || !isLetter(static_cast<unsigned char>(es[0]));
      const std::size_t e = i + es.size();
      const bool rightOk = e >= s.size() || !isLetter(static_cast<unsigned char>(s[e])) || !isLetter(static_cast<unsigned char>(es.back()));
      if (!leftOk || !rightOk) continue;
      out += en;
      i = e;
      done = true;
      break;
    }
    if (!done) out += s[i++];
  }
  return out;
}
inline std::string translate(const std::string& s, bool english) { return english ? translateWith(s, table()) : s; }
inline std::string translateLang(const std::string& s, int lang) { return lang == 1 ? translateWith(s, table()) : lang == 2 ? translateWith(s, tableRu()) : s; }

